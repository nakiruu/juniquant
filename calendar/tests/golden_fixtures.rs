//! The golden calendar fixtures (09 SKILL.md §9): rules + the checked-in seed must reproduce
//! every holiday year and every `add_trading_days` case of `nyse_calendar_cases.json`, read in
//! place (no copy, so Rust and Julia cannot drift).

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::indexing_slicing,
    reason = "integration tests: any failure must fail the test"
)]

use std::path::{Path, PathBuf};

use calendar::Calendar;
use chrono::NaiveDate;
use serde_json::Value;

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("..")
}

fn production_calendar() -> Calendar {
    let root = repo_root();
    // No runtime file: the fixtures are rules + seed only.
    Calendar::load(
        &root.join("config/nyse_calendar_overrides.toml"),
        &root.join("calendar/tests/fixtures/does-not-exist.toml"),
    )
    .unwrap()
}

fn date(v: &Value) -> NaiveDate {
    NaiveDate::parse_from_str(v.as_str().unwrap(), "%Y-%m-%d").unwrap()
}

fn cases() -> Value {
    let path =
        repo_root().join(".claude/skills/09-lock-state-machine/fixtures/nyse_calendar_cases.json");
    serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap()
}

#[test]
fn every_fixture_holiday_year_matches() {
    let cal = production_calendar();
    let fixture = cases();
    let years = fixture["holidays"].as_object().unwrap();
    assert_eq!(years.len(), 23, "fixture should hold 2018..=2040");
    let mut failures = Vec::new();
    for (year, want) in years {
        let y: i32 = year.parse().unwrap();
        let want: Vec<NaiveDate> = want.as_array().unwrap().iter().map(date).collect();
        let got = cal.holidays(y);
        if got != want {
            failures.push(format!("{y}: expected {want:?}, got {got:?}"));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

#[test]
fn every_fixture_add_trading_days_case_matches() {
    let cal = production_calendar();
    let fixture = cases();
    let list = fixture["add_trading_days"].as_array().unwrap();
    assert_eq!(list.len(), 1500);
    let mut failures = Vec::new();
    for c in list {
        let start = date(&c["start"]);
        let n = u32::try_from(c["n"].as_u64().unwrap()).unwrap();
        let expected = date(&c["expected"]);
        let got = cal.add_trading_days(start, n).unwrap();
        if got != expected {
            failures.push(format!(
                "add_trading_days({start}, {n}): expected {expected}, got {got}"
            ));
        }
    }
    assert!(
        failures.is_empty(),
        "{} failures:\n{}",
        failures.len(),
        failures.join("\n")
    );
}

/// The fixtures (2018-2040) do not cover the older seed dates; `run_fixtures.jl` checks this one
/// separately (09 SKILL.md §4).
#[test]
fn hurricane_sandy_seed_closures() {
    let cal = production_calendar();
    let d = |y, m, dd| NaiveDate::from_ymd_opt(y, m, dd).unwrap();
    assert_eq!(
        cal.add_trading_days(d(2012, 10, 26), 1).unwrap(),
        d(2012, 10, 31)
    );
    for seed in [
        d(2001, 9, 11),
        d(2001, 9, 12),
        d(2001, 9, 13),
        d(2001, 9, 14),
        d(2004, 6, 11),
        d(2007, 1, 2),
        d(2012, 10, 29),
        d(2012, 10, 30),
        d(2018, 12, 5),
        d(2025, 1, 9),
    ] {
        assert!(!cal.is_trading_day(seed), "{seed} must be closed");
    }
    assert_eq!(cal.overrides().len(), 10);
}

/// Cross-language check: the rule holidays of 1990-2100 generated by the Julia package
/// `NYSECalendar` (`calendar/tests/fixtures/rule_holidays_1990_2100.json`) equal this crate's.
#[test]
fn rule_holidays_match_julia_1990_2100() {
    let path = repo_root().join("calendar/tests/fixtures/rule_holidays_1990_2100.json");
    let fixture: Value = serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
    let years = fixture["rule_holidays"].as_object().unwrap();
    assert_eq!(years.len(), 111);
    let mut failures = Vec::new();
    for (year, want) in years {
        let y: i32 = year.parse().unwrap();
        let want: Vec<NaiveDate> = want.as_array().unwrap().iter().map(date).collect();
        let got: Vec<NaiveDate> = calendar::rule_holidays(y).iter().map(|h| h.date).collect();
        if got != want {
            failures.push(format!("{y}: julia {want:?}, rust {got:?}"));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}
